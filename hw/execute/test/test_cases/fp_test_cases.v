task test_case_fp_basic();
  t.test_case_begin( "test_case_fp_basic" );
  if ( !t.run_test ) return;

  fork
    begin : send_thread
      // 11.375 + 5.563 = 16.938
      send( 32'b01000001001101100000000000000001, // A = 11.375
            32'b01000000101100100000010000011011 ); // B = 5.563
      #20;

      // 59.979 + 6.5 = 66.479
      send( 32'b01000010011011111110101110000101, // A = 59.979
            32'b01000000110100000000000000000000 ); // B = 6.5
      #20;

      // 1000.5 + 981.654 = 1982.154
      send( 32'b01000100011110100010000000000000, // A = 1000.5
            32'b01000100011101010110100111011011 ); // B = 981.654
      #20;

      // 549.987 + 5.563 = 555.550
      send( 32'b01000100000010010111111100101011, // A = 549.987
            32'b01000000101100100000010000011001 ); // B = 5.563
      #20;
    end

    begin : recv_thread
      // Expected results — each corresponds to the sum above
      recv( 32'b01000010000001100011110001110001 ); // 16.938
      recv( 32'b01000010100001010111101011011010 ); // 66.479
      recv( 32'b01000100111101111110001001100000 ); // 1982.154
      recv( 32'b01000100000010101111001000010100 ); // 555.550
    end
  join

  t.test_case_end();
endtask


